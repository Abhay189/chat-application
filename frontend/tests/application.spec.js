import { Buffer } from "node:buffer";
import { test, expect } from "@playwright/test";

const password = "Browser-test-password-123";
async function register(page, handle) {
  await page.goto("/");
  await page.getByRole("button", { name: "Create an account" }).click();
  await page.getByLabel("Name", { exact: true }).fill(handle);
  await page.getByLabel("Username", { exact: true }).fill(handle);
  await page.getByLabel("Email", { exact: true }).fill(`${handle}@example.com`);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.locator('button[type="submit"]').click();
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible();
}
async function login(page, handle) {
  await page.getByLabel("Email", { exact: true }).fill(`${handle}@example.com`);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await expect(page.getByRole("button", { name: "New chat", exact: true })).toBeVisible();
}

test("two accounts: contacts, search, chat, edit/delete, persistence, settings, logout", async ({ page, browser }) => {
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const suffix = Date.now().toString(36);
  const alice = `alice_${suffix}`;
  const bob = `bob_${suffix}`;
  const otherContext = await browser.newContext();
  const other = await otherContext.newPage();
  await register(page, alice);
  await register(other, bob);
  await login(page, alice);
  await login(other, bob);
  await page.reload();
  await expect(page.getByRole("button", { name: "New chat" })).toBeVisible();
  await page.getByRole("button", { name: "New chat" }).click();
  const search = page.getByRole("textbox", { name: "Search by username or email" });
  await search.fill(`${bob}@example.com`);
  await page.getByRole("button", { name: `Add ${bob} to contacts`, exact: true }).click();
  await expect(page.getByRole("button", { name: `Chat with ${bob}`, exact: true })).toBeVisible();
  await page.getByRole("button", { name: `Chat with ${bob}`, exact: true }).click();
  await page.getByRole("textbox", { name: "Message", exact: true }).fill("Hello from Alice");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(page.locator(".message-content").getByText("Hello from Alice", { exact: true })).toBeVisible();
  await expect(other.getByRole("button", { name: new RegExp(alice) })).toBeVisible({ timeout: 12000 });
  await other.getByRole("button", { name: new RegExp(alice) }).click();
  await expect(other.locator(".message-content").getByText("Hello from Alice", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Edit message", exact: true }).click();
  await page.getByRole("textbox", { name: "Message", exact: true }).fill("Edited on server");
  await page.getByRole("button", { name: "Save message", exact: true }).click();
  await expect(other.locator(".message-content").getByText("Edited on server", { exact: true })).toBeVisible({ timeout: 12000 });
  await page.getByRole("button", { name: "Delete message", exact: true }).click();
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  await expect(other.locator(".message-content")).toHaveCount(0, { timeout: 12000 });
  await page.getByRole("button", { name: "Attach file", exact: true }).click();
  await page.locator('input[type="file"]').setInputFiles({ name: "notes.txt", mimeType: "text/plain", buffer: Buffer.from("Saved in PostgreSQL") });
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(other.getByRole("link", { name: "Download attachment" })).toBeVisible({ timeout: 12000 });
  const downloadPromise = other.waitForEvent("download");
  await other.getByRole("link", { name: "Download attachment" }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe("notes.txt");
  await expect(page.getByRole("button", { name: "Back", exact: true })).toBeHidden();
  await page.screenshot({ path: "test-results/chat-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Profile", exact: true }).first().click();
  await expect(page.getByRole("heading", { name: alice, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Edit profile" }).click();
  await page.getByLabel("Name", { exact: true }).fill("Updated Alice");
  await page.getByLabel("Bio", { exact: true }).fill("Saved profile biography");
  await page.getByRole("button", { name: "Save Changes" }).click();
  await expect(page.getByText("Saved profile biography", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Updated Alice", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Dark", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.reload();
  await expect(page.getByRole("button", { name: "Settings", exact: true })).toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("button", { name: "Dark", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("switch", { name: "Notification sound" }).click();
  await expect(page.getByRole("switch", { name: "Notification sound" })).toHaveAttribute("aria-checked", "false");
  await page.getByRole("button", { name: "Log out", exact: true }).first().click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Log out", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible();
  await login(page, alice);
  await page.getByRole("button", { name: "New chat", exact: true }).click();
  await expect(page.getByRole("button", { name: `Chat with ${bob}`, exact: true })).toBeVisible();
  await search.fill(bob);
  await expect(page.getByRole("button", { name: `Chat with ${bob}`, exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/contacts-dark.png", fullPage: true });
  expect(errors).toEqual([]);
  await otherContext.close();
});

test("required email and mobile layout", async ({ page, browser }) => {
  const handle = `mobile_${Date.now().toString(36)}`;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.getByRole("button", { name: "Create an account" }).click();
  await expect(page.getByLabel("Email", { exact: true })).toHaveAttribute("required", "");
  const otherContext = await browser.newContext();
  const other = await otherContext.newPage();
  const friend = handle + "_friend";
  await register(other, friend);
  await register(page, handle);
  await login(page, handle);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Settings", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Dark", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: handle, exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/settings-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Chats", exact: true }).click();
  await page.getByRole("button", { name: "New chat", exact: true }).click();
  await page.getByRole("textbox", { name: "Search by username or email" }).fill(friend);
  await page.getByRole("button", { name: `Add ${friend} to contacts`, exact: true }).click();
  await page.getByRole("button", { name: `Chat with ${friend}`, exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Message", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/chat-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await expect(page.getByRole("button", { name: "New chat", exact: true })).toBeVisible();
  await otherContext.close();
});
